#!/usr/bin/env node
// Bundles the text assets the Worker serves (SDK, guide, web page JS/CSS)
// into src/generated/assets.ts so both wrangler (esbuild) and vitest (vite)
// can import them without loader-specific configuration.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = {
  SDK_JS: "src/sdk.js",
  GUIDE_MD: "src/guide.md",
  DASHBOARD_JS: "src/dashboard/dashboard.js",
  VIZ_JS: "src/dashboard/viz.js",
  FORMELAB_CSS: "src/dashboard/formelab.css",
  HOME_CSS: "src/dashboard/home.css",
  THEME_JS: "src/dashboard/theme.js",
  SITE_JS: "src/dashboard/site.js",
  SIGNIN_JS: "src/dashboard/signin.js",
  CONSENT_JS: "src/dashboard/consent.js",
  SKILL_MD: "skill/SKILL.md",
  CHANGELOG_MD: "CHANGELOG.md",
  INSTALL_JS: "src/dashboard/install.js",
  SW_JS: "src/dashboard/sw.js",
};
// Images and fonts, bundled as base64 (the app icons for installing Formelab on a device).
const binaryAssets = {
  ICON_192_PNG: "src/dashboard/icons/icon-192.png",
  ICON_512_PNG: "src/dashboard/icons/icon-512.png",
  MASKABLE_512_PNG: "src/dashboard/icons/maskable-512.png",
  APPLE_TOUCH_ICON_PNG: "src/dashboard/icons/apple-touch-icon.png",
  // Fonts for drawing link preview cards (see src/share.ts). SIL Open Font License.
  DISPLAY_FONT_TTF: "src/fonts/BricolageGrotesque_800ExtraBold.ttf",
  TEXT_FONT_TTF: "src/fonts/Inter_600SemiBold.ttf",
};

export function generateAssets() {
  let out = "// Generated by scripts/gen-assets.mjs. Do not edit.\n";
  const hash = createHash("sha256");
  for (const [name, rel] of Object.entries(assets)) {
    const body = readFileSync(join(root, rel), "utf8");
    hash.update(body);
    out += `export const ${name} = ${JSON.stringify(body)};\n`;
  }
  for (const [name, rel] of Object.entries(binaryAssets)) {
    const body = readFileSync(join(root, rel));
    hash.update(body);
    out += `export const ${name} = ${JSON.stringify(body.toString("base64"))};\n`;
  }
  // Added to asset URLs (?v=...) so browsers fetch new scripts and styles right after a deploy.
  out += `export const ASSET_VERSION = ${JSON.stringify(hash.digest("hex").slice(0, 10))};\n`;
  const target = join(root, "src/generated/assets.ts");
  mkdirSync(dirname(target), { recursive: true });
  let previous = "";
  try {
    previous = readFileSync(target, "utf8");
  } catch {}
  if (previous !== out) writeFileSync(target, out);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) generateAssets();
